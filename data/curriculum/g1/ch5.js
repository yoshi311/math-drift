function circ(opt = {}) {
  const cx = 140, cy = 125, R = 90;
  let s = opt.half ? `<path d="M${cx - R},${cy} A${R},${R} 0 0 1 ${cx + R},${cy} Z" fill="rgba(0,229,255,.1)" stroke="${CY}" stroke-width="2.5"/>`
    : `<circle cx="${cx}" cy="${cy}" r="${R}" fill="rgba(0,229,255,.1)" stroke="${CY}" stroke-width="2.5"/>`;
  if (opt.hole) s += `<circle cx="${cx}" cy="${cy}" r="${R * 0.43}" fill="#0b1020" stroke="${CY}" stroke-width="2.5"/>` + ln(cx, cy, cx - R * 0.43, cy, RE, 2, '5 4') + t(cx - 20, cy - 8, opt.hole, RE);
  s += dot(cx, cy) + t(cx - 6, cy + 22, 'O');
  if (opt.chord) s += ln(cx - 80, cy - 41, cx + 62, cy - 65, YE) + dot(cx - 80, cy - 41) + dot(cx + 62, cy - 65) + t(cx - 94, cy - 46, 'A') + t(cx + 74, cy - 74, 'B');
  if (opt.diam) s += ln(cx - R, cy, cx + R, cy, YE);
  if (opt.tan) s += ln(cx, cy, cx + R, cy, TX, 2) + ln(cx + R, cy - 110, cx + R, cy + 110, YE) + dot(cx + R, cy) + t(cx + R + 14, cy + 22, 'A') + t(cx + R + 14, cy - 96, 'ℓ', YE) + (opt.q ? `<path d="M${cx + R - 22},${cy} A22,22 0 0 1 ${cx + R},${cy - 22}" fill="none" stroke="${RE}" stroke-width="2.2"/>` + t(cx + R - 26, cy - 22, '?', RE) : '');
  if (opt.r) s += ln(cx, cy, cx + R, cy, YE, 2, '5 4') + t(cx + R / 2, cy - 8, opt.r, YE);
  if (opt.d) s += ln(cx - R, cy, cx + R, cy, YE, 2, '5 4') + t(cx + 40, cy - 8, opt.d, YE);
  return raw(opt.tan ? 300 : 280, 250, s);
}


// 方眼上の図形の移動
function gridFig() {
  const u = 28, W = 12, H = 8, ox = 10, oy = 10;
  let s = '';
  for (let i = 0; i <= W; i++) s += `<line x1="${ox + i * u}" y1="${oy}" x2="${ox + i * u}" y2="${oy + H * u}" stroke="#2a3145"/>`;
  for (let j = 0; j <= H; j++) s += `<line x1="${ox}" y1="${oy + j * u}" x2="${ox + W * u}" y2="${oy + j * u}" stroke="#2a3145"/>`;
  const P = pts => pts.map(([x, y]) => `${ox + x * u},${oy + y * u}`).join(' ');
  const tri = (pts, c, label) => {
    const cx = pts.reduce((a, p) => a + p[0], 0) / 3, cy = pts.reduce((a, p) => a + p[1], 0) / 3;
    return `<polygon points="${P(pts)}" fill="${c}" fill-opacity=".25" stroke="${c}" stroke-width="2.5"/>${t(ox + cx * u, oy + cy * u + 6, label)}`;
  };
  s += `<line x1="${ox}" y1="${oy + 4 * u}" x2="${ox + 6 * u}" y2="${oy + 4 * u}" stroke="${YE}" stroke-width="2" stroke-dasharray="6 5"/>${t(ox + 6 * u + 14, oy + 4 * u + 6, 'ℓ', YE)}`;
  s += `<circle cx="${ox + 5.5 * u}" cy="${oy + 4 * u}" r="4" fill="${RE}"/>${t(ox + 5.5 * u + 2, oy + 4 * u - 8, 'O', RE)}`;
  s += tri([[1, 1], [4, 1], [1, 3]], CY, 'ア') + tri([[7, 1], [10, 1], [7, 3]], '#2bff88', 'イ') + tri([[1, 7], [4, 7], [1, 5]], '#b26bff', 'ウ') + tri([[10, 7], [7, 7], [10, 5]], RE, 'エ');
  return raw(W * u + 20, H * u + 20, s);
}

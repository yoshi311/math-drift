const CY = '#00e5ff', YE = '#ffd400', MU = '#7f8aa3', TX = '#eef2f8';
const t = (x, y, s, c = TX) => `<text x="${x}" y="${y}" text-anchor="middle" fill="${c}" font-weight="700" font-size="16">${s}</text>`;
const L = (x1, y1, x2, y2, d) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${d ? MU : CY}" stroke-width="2.5"${d ? ' stroke-dasharray="6 5"' : ''}/>`;

// 直方体ABCD-EFGH（上面ABCD、手前の面ABFE）
const BOX = (() => {
  const A = [50, 80], B = [210, 80], F = [210, 190], E = [50, 190], d = [60, -45];
  const D = [A[0] + d[0], A[1] + d[1]], Cc = [B[0] + d[0], B[1] + d[1]], G = [F[0] + d[0], F[1] + d[1]], H = [E[0] + d[0], E[1] + d[1]];
  return raw(300, 215, L(...A, ...B) + L(...B, ...F) + L(...F, ...E) + L(...E, ...A) + L(...A, ...D) + L(...B, ...Cc) + L(...F, ...G) + L(...D, ...Cc) + L(...Cc, ...G) +
    L(...D, ...H, 1) + L(...H, ...G, 1) + L(...E, ...H, 1) +
    t(A[0] - 12, A[1] + 4, 'A') + t(B[0] + 4, B[1] + 18, 'B') + t(F[0] + 4, F[1] + 18, 'F') + t(E[0] - 12, E[1] + 4, 'E') + t(D[0] - 6, D[1] - 6, 'D') + t(Cc[0] + 12, Cc[1] - 2, 'C') + t(G[0] + 12, G[1] + 4, 'G') + t(H[0] - 14, H[1] + 2, 'H'));
})();

// 投影図（上：立面図、下：平面図）
function proj(top, bottom) {
  const shape = (k, y) => {
    if (k === 'tri') return `<path d="M60,${y + 80} L180,${y + 80} L120,${y}Z" fill="none" stroke="${CY}" stroke-width="2.5"/>`;
    if (k === 'rect') return `<rect x="60" y="${y}" width="120" height="80" fill="none" stroke="${CY}" stroke-width="2.5"/>`;
    if (k === 'circle') return `<circle cx="120" cy="${y + 40}" r="40" fill="none" stroke="${CY}" stroke-width="2.5"/>`;
    if (k === 'sqx') return `<rect x="80" y="${y}" width="80" height="80" fill="none" stroke="${CY}" stroke-width="2.5"/><line x1="80" y1="${y}" x2="160" y2="${y + 80}" stroke="${CY}" stroke-width="2"/><line x1="160" y1="${y}" x2="80" y2="${y + 80}" stroke="${CY}" stroke-width="2"/>`;
    if (k === 'tri2') return `<path d="M60,${y + 80} L180,${y + 80} L100,${y}Z" fill="none" stroke="${CY}" stroke-width="2.5"/>`;
    return '';
  };
  return raw(240, 220, shape(top, 10) + `<line x1="20" y1="105" x2="220" y2="105" stroke="${MU}" stroke-width="1.5"/>` + shape(bottom, 120) +
    `<text x="226" y="54" fill="${MU}" font-size="12" text-anchor="end">立面図</text><text x="226" y="164" fill="${MU}" font-size="12" text-anchor="end">平面図</text>`);
}


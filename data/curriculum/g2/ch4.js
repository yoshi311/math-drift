// 三角形
function tri(lab = {}, ext = null) {
  const pts = { A: [170, 40], B: [60, 190], C: [290, 190], _D: [350, 190] };
  const angles = [];
  if (lab.A) angles.push({ at: 'A', from: 'B', to: 'C', label: lab.A, r: 26 });
  if (lab.B) angles.push({ at: 'B', from: 'C', to: 'A', label: lab.B, r: 26 });
  if (lab.C && !ext) angles.push({ at: 'C', from: 'A', to: 'B', label: lab.C, r: 26 });
  if (ext) angles.push({ at: 'C', from: '_D', to: 'A', label: ext, r: 22, lr: 20 });
  return geo({ w: 370, h: 220, pts, polys: [['A', 'B', 'C']], lines: ext ? [{ p: [290, 190, 360, 190] }] : [], angles, labelOff: { B: [-12, 8], C: [6, 22], A: [0, -12] } });
}

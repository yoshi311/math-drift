// 2直線の交わり（対頂角）
function cross(lab = {}) {
  const O = [180, 110], p = { _O: O };
  const R = { a: [[320, 180], [300, 30]], b: [[300, 30], [40, 40]], c: [[40, 40], [60, 190]], d: [[60, 190], [320, 180]] };
  const angles = Object.entries(lab).map(([k, v]) => ({ at: '_O', from: R[k][0], to: R[k][1], label: v, r: 26 }));
  return geo({ w: 360, h: 220, pts: p, lines: [{ p: [40, 40, 320, 180] }, { p: [60, 190, 300, 30] }], angles });
}
// 平行線（または2直線）と1本の直線
function par(lab = {}, parallel = true) {
  const P = [140, 70], Q = [220, 170];
  const R = {
    a: ['_P', [330, 70], [100, 20]], b: ['_P', [100, 20], [20, 70]], c: ['_P', [20, 70], Q], d: ['_P', Q, [330, 70]],
    e: ['_Q', [330, 170], P], f: ['_Q', P, [20, 170]], g: ['_Q', [20, 170], [260, 220]], h: ['_Q', [260, 220], [330, 170]],
  };
  const angles = Object.entries(lab).map(([k, v]) => ({ at: R[k][0], from: R[k][1], to: R[k][2], label: v, r: Object.keys(lab).length > 2 ? 13 : 20, lr: 13 }));
  return geo({ w: 360, h: 230, pts: { _P: P, _Q: Q, _a: [20, 70], _b: [330, 70], _c: [20, 170], _d: [330, 170] },
    lines: [{ p: [20, 70, 330, 70], label: 'ℓ', lx: 336, ly: 75 }, { p: [20, 170, 330, 170], label: 'm', lx: 336, ly: 175 }, { p: [100, 20, 260, 220], label: 'n', lx: 266, ly: 222 }],
    par: parallel ? [{ s: ['_a', '_b'] }, { s: ['_c', '_d'] }] : [], angles });
}

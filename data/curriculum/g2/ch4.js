// n角形（内角の記号 ins、または外角の記号 exs）
function ngon(n, ins = [], exs = []) {
  const cx = 180, cy = 125, R = 92, pts = {}, names = [];
  for (let i = 0; i < n; i++) { const t = -Math.PI / 2 + 2 * Math.PI * i / n; const k = '_' + i; pts[k] = [cx + R * Math.cos(t), cy + R * Math.sin(t)]; names.push(k); }
  const angles = [], lines = [];
  ins.forEach((lab, i) => lab && angles.push({ at: names[i], from: names[(i + 1) % n], to: names[(i + n - 1) % n], label: lab, r: 20, lr: 16 }));
  exs.forEach((lab, i) => {
    if (!lab) return; const p = pts[names[i]], q = pts[names[(i + n - 1) % n]], e = [p[0] + (p[0] - q[0]) * 0.45, p[1] + (p[1] - q[1]) * 0.45];
    lines.push({ p: [...p, ...e], c: '#7f8aa3' }); angles.push({ at: names[i], from: e, to: names[(i + 1) % n], label: lab, r: 18, lr: 16 });
  });
  return geo({ w: 360, h: 250, pts, polys: [names], lines, angles });
}

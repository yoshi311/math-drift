// 二等辺三角形 AB＝AC
// opt: D（頂角の二等分線）、right、ext（Cの外角）、DE（BD＝CEの点）、noTicks、texts
function iso(lab = {}, opt = {}) {
  const pts = { A: [170, 30], B: [80, 200], C: [260, 200] };
  if (opt.D) pts.D = [170, 200];
  if (opt.DE) { pts.D = [125, 200]; pts.E = [215, 200]; }
  if (opt.ext) pts._e = [330, 200];
  const angles = [], segs = [], ticks = opt.noTicks ? [] : [{ s: ['A', 'B'] }, { s: ['A', 'C'] }];
  if (lab.A) angles.push({ at: 'A', from: 'B', to: 'C', label: lab.A, r: 26 });
  if (lab.B) angles.push({ at: 'B', from: 'C', to: 'A', label: lab.B, r: 26 });
  if (lab.C) angles.push({ at: 'C', from: 'A', to: 'B', label: lab.C, r: 26 });
  if (opt.D) segs.push(['A', 'D', '#ffd400']);
  if (opt.DE) { segs.push(['A', 'D', '#ffd400'], ['A', 'E', '#ffd400']); ticks.push({ s: ['B', 'D'], n: 2 }, { s: ['E', 'C'], n: 2 }); }
  if (opt.ext) { segs.push(['C', '_e', '#eef2f8']); angles.push({ at: 'C', from: '_e', to: 'A', label: opt.ext, r: 22 }); }
  return geo({ w: 350, h: 235, pts, polys: [['A', 'B', 'C']], segs, ticks, angles, rights: opt.right ? [['A', 'D', 'C']] : [], texts: opt.texts || [], labelOff: { B: [-12, 8], C: [6, 14], D: [0, 24], E: [0, 24] } });
}
// 正三角形 ABC（1辺180）。opt: ext（Cの外角）、CD（CD＝CAの点D）、onBC（辺BC上の点D）
function eqtri(lab = {}, opt = {}) {
  const pts = { A: [170, 30], B: [80, 186], C: [260, 186] };
  const angles = [], segs = [];
  if (opt.ext || opt.CD) pts[opt.CD ? 'D' : '_e'] = opt.CD ? [440, 186] : [340, 186];
  if (opt.onBC) pts.D = [140, 186];
  if (lab.A) angles.push({ at: 'A', from: 'B', to: 'C', label: lab.A, r: 26 });
  if (lab.B) angles.push({ at: 'B', from: 'C', to: 'A', label: lab.B, r: 26 });
  if (opt.ext) { segs.push(['C', '_e', '#eef2f8']); angles.push({ at: 'C', from: '_e', to: 'A', label: opt.ext, r: 22 }); }
  if (opt.CD) { segs.push(['C', 'D', '#eef2f8'], ['A', 'D', '#ffd400']); angles.push({ at: 'A', from: 'C', to: 'D', label: x, r: 40 }); }
  if (opt.onBC) { segs.push(['A', 'D', '#ffd400']); angles.push({ at: 'A', from: 'B', to: 'D', label: '20°', r: 44, lr: 12 }, { at: 'D', from: 'C', to: 'A', label: x, r: 22 }); }
  const ticks = [{ s: ['A', 'B'] }, { s: ['B', 'C'] }, { s: ['A', 'C'] }];
  if (opt.CD) ticks.push({ s: ['C', 'D'] });
  return geo({ w: opt.CD ? 470 : 360, h: 215, pts, polys: [['A', 'B', 'C']], segs, ticks, angles, labelOff: { B: [-12, 8], C: [4, 16], D: [8, 18] } });
}
// 2つの直角三角形。n＝[上の頂点, 底辺の右端, 直角の頂点] の名前（左右1組ずつ）。t：等しい辺の印、a：等しい角の印
function rt2(n1, n2, t = [], a = []) {
  const pts = {};
  [[40, 40], [190, 175], [40, 175]].forEach((p, i) => { pts[n1[i]] = p; });
  [[230, 40], [380, 175], [230, 175]].forEach((p, i) => { pts[n2[i]] = p; });
  const ticks = t.map(([s, k]) => ({ s, n: k }));
  const angles = a.map(([at, from, to]) => ({ at, from, to, label: '', r: 24 }));
  return geo({ w: 420, h: 210, pts, polys: [n1, n2], ticks, angles, rights: [[n1[0], n1[2], n1[1]], [n2[0], n2[2], n2[1]]], labelOff: { [n1[1]]: [10, 8], [n1[2]]: [-10, 8], [n2[1]]: [10, 8], [n2[2]]: [-10, 8] } });
}

// 平行四辺形。lab：角の記号。opt: O（対角線）、AC（対角線ACのみ）、E（∠Aの二等分線とBCの交点）、onAD（AD上の点Eと△EBC）、EF（AC上のE、F）、texts、noPar
function pgram(lab = {}, opt = {}) {
  const pts = { A: [100, 40], B: [50, 190], C: [270, 190], D: [320, 40] };
  if (opt.O) pts.O = [185, 115];
  const angles = [], segs = [];
  if (lab.A) angles.push({ at: 'A', from: 'B', to: 'D', label: lab.A, r: 24 });
  if (lab.B) angles.push({ at: 'B', from: 'C', to: 'A', label: lab.B, r: 24 });
  if (lab.C) angles.push({ at: 'C', from: 'D', to: 'B', label: lab.C, r: 24 });
  if (lab.D) angles.push({ at: 'D', from: 'A', to: 'C', label: lab.D, r: 24 });
  if (opt.O) segs.push(['A', 'C'], ['B', 'D']);
  if (opt.AC) segs.push(['A', 'C', '#ffd400']);
  if (opt.E) { pts.E = [208, 190]; segs.push(['A', 'E', '#ffd400']); angles.push({ at: 'E', from: 'B', to: 'A', label: x, r: 22 }); }
  if (opt.onAD) { pts.E = [200, 40]; segs.push(['E', 'B', '#ffd400'], ['E', 'C', '#ffd400']); }
  if (opt.EF) { pts.O = [185, 115]; pts.E = [142, 78]; pts.F = [228, 152]; segs.push(['A', 'C', '#7f8aa3'], ['B', 'D', '#7f8aa3'], ['E', 'B', '#ffd400'], ['B', 'F', '#ffd400'], ['F', 'D', '#ffd400'], ['D', 'E', '#ffd400']); }
  const par = opt.noPar ? [] : [{ s: ['B', 'C'] }, { s: ['A', 'D'] }, { s: ['B', 'A'], n: 2 }, { s: ['C', 'D'], n: 2 }];
  return geo({ w: 370, h: 225, pts, polys: [['A', 'B', 'C', 'D']], segs, par, ticks: opt.ticks || [], angles, texts: opt.texts || [], labelOff: { B: [-12, 8], C: [12, 8], A: [-6, -10], D: [8, -10], O: [0, 26], E: [opt.E ? 6 : 0, opt.E ? 18 : -10], F: [12, 12] } });
}
// 四角形ABCD（平行四辺形になる条件）。平行の印・等しい辺の印・等しい角の印を、与えられた条件だけ付ける
function quad({ par = [], ticks = [], angs = [], O = false, trapz = false } = {}) {
  const pts = trapz ? { A: [70, 40], B: [70, 200], C: [300, 160], D: [300, 80] } : { A: [100, 40], B: [50, 190], C: [270, 190], D: [320, 40] };
  if (O) pts.O = [185, 115];
  const nb = { A: ['B', 'D'], B: ['C', 'A'], C: ['D', 'B'], D: ['A', 'C'] };
  return geo({ w: 370, h: 225, pts, polys: [['A', 'B', 'C', 'D']], segs: O ? [['A', 'C'], ['B', 'D']] : [],
    par: par.map(([s, n]) => ({ s, n })), ticks: ticks.map(([s, n]) => ({ s, n })),
    angles: angs.map(([k, n]) => ({ at: k, from: nb[k][0], to: nb[k][1], label: '', r: n === 2 ? 16 : 24 })),
    labelOff: { B: [-12, 8], C: [12, 8], A: [-6, -10], D: [8, -10], O: [0, 26] } });
}
